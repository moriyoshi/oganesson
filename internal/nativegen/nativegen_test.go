const hashGo = `package hash

import (
	"context"
	"errors"
	"time"
)

// Meta is attached to a hash.
type Meta struct {
	Base
	Algorithm string            ` + "`json:\"algorithm\"`" + `
	Cost      int               ` + "`json:\"cost,omitempty\"`" + `
	Size      int64             ` + "`json:\"size\"`" + `
	Salt      []byte            ` + "`json:\"salt\"`" + `
	At        time.Time         ` + "`json:\"at\"`" + `
	Labels    map[string]string ` + "`json:\"labels\"`" + `
	Parent    *Meta             ` + "`json:\"parent\"`" + `
	secret    string
	Ignored   string ` + "`json:\"-\"`" + `
}

// Base is embedded.
type Base struct {
	ID string ` + "`json:\"id\"`" + `
}

// Level is a named number.
type Level int

// Stamp is a named time.Time, declared in the file that imports "time".
type Stamp time.Time

// HashPassword hashes a password.
// It is slow on purpose.
func HashPassword(password string, level Level) ([]byte, error) { return nil, errors.New("x") }

// Verify checks a password (asynchronous: it takes a context).
func Verify(ctx context.Context, password string, hash []byte) (bool, error) { return false, nil }

// CurrentTime is the time.
//
//og:name now
//nolint:all
func CurrentTime() time.Time { return time.Now() }

//og:sync
func Describe(ctx context.Context, m Meta) *Meta { return nil }

//og:async
func URLFor(ids []string) map[string][]int { return nil }

//og:skip
func Internal() {}

func unexported() {}

func Reset() error { return nil }

// Scale doubles n (a top-level int64 crosses as a bigint).
func Scale(n int64) int64 { return 2 * n }
`

// TestScan: a project's og/ module read as native modules: names
// (lowerCamel, initialisms, //og:name), the async rule (a leading
// context.Context, //og:async, //og:sync), //og:skip, TypeScript for
// parameters and results (with the package's structs by json tags,
// embedded ones flattened), doc comments as JSDoc, and the Go glue.
func TestScan(t *testing.T) {
	dir := t.TempDir()
	write := func(name, src string) {
		p := filepath.Join(dir, filepath.FromSlash(name))
		_ = os.MkdirAll(filepath.Dir(p), 0o755)
		if err := os.WriteFile(p, []byte(src), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("og/go.mod", "module example.com/app/og\n\ngo 1.27.0\n")
	write("og/hash/hash.go", hashGo)
	// A second file that uses Stamp (a time.Time alias) without importing
	// "time": its underlying type must resolve with hash.go's imports, not
	// this file's. Sorts after hash.go, so touch is emitted last.
	write("og/hash/use.go", "package hash\n\n// Touch stamps a value.\nfunc Touch(s Stamp) Stamp { return s }\n")
	write("og/hash/hash_test.go", "package hash\n\nfunc TestNothing() {}\n")
	write("og/empty/README.md", "no Go here\n")
	p, err := Scan(dir)
	if err != nil {
		t.Fatal(err)
	}
	if got := strings.Join(p.Names(), ","); got != "hash" || p.ModulePath != "example.com/app/og" {
		t.Fatalf("modules %q, module path %q", got, p.ModulePath)
	}
	wantTS := `
// Native Go modules (og/<name>), generated by og build.
declare module "og:hash" {
  export interface Meta {
    id: string;
    algorithm: string;
    cost?: number;
    size: bigint;
    salt: string;
    at: string;
    labels: Record<string, string>;
    parent: Meta | null;
  }
  /**
   * HashPassword hashes a password.
   * It is slow on purpose.
   */
  export function hashPassword(password: string, level: number): Uint8Array;
  /**
   * Verify checks a password (asynchronous: it takes a context).
   */
  export function verify(password: string, hash: Uint8Array): Promise<boolean>;
  /**
   * CurrentTime is the time.
   */
  export function now(): Date;
  export function describe(m: Meta): Meta | null;
  export function urlFor(ids: string[]): Promise<Record<string, number[]>>;
  export function reset(): void;
  /**
   * Scale doubles n (a top-level int64 crosses as a bigint).
   */
  export function scale(n: bigint): bigint;
  /**
   * Touch stamps a value.
   */
  export function touch(s: Date): Date;
}
`
	if got := p.TypeScript(); got != wantTS {
		t.Errorf("TypeScript:\n%s\nwant\n%s", got, wantTS)
	}
	glue, err := p.Glue("main")
	if err != nil {
		t.Fatal(err)
	}
	wantGlue := `// Code generated by og build from og/; DO NOT EDIT.

package main

import (
	og_hash "example.com/app/og/hash"
	"github.com/moriyoshi/oganesson/runtime/native"
)

func init() {
	native.Register(native.Module{Name: "hash", Funcs: []native.Func{
		{Name: "hashPassword", Fn: og_hash.HashPassword, Async: false},
		{Name: "verify", Fn: og_hash.Verify, Async: true},
		{Name: "now", Fn: og_hash.CurrentTime, Async: false},
		{Name: "describe", Fn: og_hash.Describe, Async: false},
		{Name: "urlFor", Fn: og_hash.URLFor, Async: true},
		{Name: "reset", Fn: og_hash.Reset, Async: false},
		{Name: "scale", Fn: og_hash.Scale, Async: false},
		{Name: "touch", Fn: og_hash.Touch, Async: false},
	}})
}
`
	if string(glue) != wantGlue {
		t.Errorf("glue:\n%s\nwant\n%s", glue, wantGlue)
	}
}

// TestScanRejects: names og uses itself, JavaScript name clashes, and a
// project without og/go.mod (none).
func TestScanRejects(t *testing.T) {
	for _, c := range []struct {
		files map[string]string
		err   string
	}{
		{map[string]string{"og/go.mod": "module m\n", "og/kv/kv.go": "package kv\nfunc Get() {}\n"}, "og:kv is not a usable module name"},
		{map[string]string{"og/go.mod": "module m\n", "og/a/a.go": "package a\nfunc Hash() {}\n//og:name hash\nfunc Other() {}\n"}, `are both "hash"`},
	} {
		dir := t.TempDir()
		for name, src := range c.files {
			p := filepath.Join(dir, filepath.FromSlash(name))
			_ = os.MkdirAll(filepath.Dir(p), 0o755)
			_ = os.WriteFile(p, []byte(src), 0o644)
		}
		if _, err := Scan(dir); err == nil || !strings.Contains(err.Error(), c.err) {
			t.Errorf("%v: %v (want %q)", c.files, err, c.err)
		}
	}
	if p, err := Scan(t.TempDir()); p != nil || err != nil {
		t.Errorf("no og/: %v %v", p, err)
	}
}

func TestLowerCamel(t *testing.T) {
	for in, want := range map[string]string{"HashPassword": "hashPassword", "URLFor": "urlFor", "ID": "id", "X": "x", "HTTPServerURL": "httpServerURL", "already": "already"} {
		if got := lowerCamel(in); got != want {
			t.Errorf("lowerCamel(%q) = %q, want %q", in, got, want)
		}
	}
}
