#!/bin/sh
# Writes the license texts of Oganesson and of every third-party component
# linked or embedded into og. The output is checked in as
# runtime/notices/THIRD_PARTY_NOTICES.txt and embedded into og (`og
# licenses`), packaged app binaries (`-licenses`), and ejected modules:
#
#   scripts/collect-notices.sh [out]   (or: go generate ./runtime/notices)
#
# - Oganesson's own LICENSE comes first.
# - Go: the toolchain's LICENSE, then every module in
#   `go list -deps -tags nodynamic ./cmd/og`, unioned over the release
#   targets (OG_NOTICE_TARGETS overrides the list), since the set differs per
#   platform (e.g. go-winio on windows).
# - TypeScript-Go: the replaced module's LICENSE plus the repository's
#   NOTICE.txt, which Apache-2.0 section 4(d) requires to be passed along.
# - Vendored Go (third_party/goja_nodejs) and vendored JS: the license files
#   shipped in each vendored tree.
#
# Deterministic (no paths, no toolchain version), so CI can diff it. Fails
# when a component has no license file, so a new dependency cannot ship
# unattributed. Needs third_party/typescript (scripts/sync-typescript.sh).
set -eu
export LC_ALL=C
root=$(cd "$(dirname "$0")/.." && pwd)
out=${1:-"$root/runtime/notices/THIRD_PARTY_NOTICES.txt"}
case $out in /*) ;; *) out="$(pwd)/$out" ;; esac
targets=${OG_NOTICE_TARGETS:-"linux/amd64 linux/arm64 darwin/amd64 darwin/arm64 windows/amd64 windows/arm64"}
tmp=$(mktemp)
trap 'rm -f "$tmp" "$tmp.missing" "$tmp.mods"' EXIT

section() { # title file...
  title=$1; shift
  printf '%s\n%s\n\n' "================================================================================" "$title" >>"$tmp"
  for f in "$@"; do
    printf -- '--- %s\n\n' "$(basename "$f")" >>"$tmp"
    cat "$f" >>"$tmp"
    printf '\n\n' >>"$tmp"
  done
}

license_files() { # dir
  find "$1" -maxdepth 1 -type f \( -iname 'LICEN[CS]E*' -o -iname 'COPYING*' -o -iname 'NOTICE*' \) | sort
}

cat >"$tmp" <<'EOF'
Oganesson and the third-party software it includes

This text is embedded into og (`og licenses`), into every app binary made
with `og build -o` (`<app> -licenses`), and into modules made with
`og build -eject`. It covers Oganesson's own Go and JavaScript code. In an
app binary or ejected module it is followed by the licenses of the npm
packages og build bundled into that app.

Generated by scripts/collect-notices.sh; do not edit.

EOF

cd "$root"
section "Oganesson (github.com/moriyoshi/oganesson)" LICENSE

# Homebrew keeps the toolchain's LICENSE one level above GOROOT.
goroot=$(go env GOROOT)
for golicense in "$goroot/LICENSE" "$goroot/../LICENSE" ""; do
  [ -f "$golicense" ] && break
done
if [ -z "$golicense" ]; then
  echo "collect-notices: no LICENSE found for the Go toolchain at $goroot" >&2
  exit 1
fi
section "Go (the Go standard library and runtime)" "$golicense"

# -e: runtime/notices embeds this file, which may not exist yet.
for target in $targets; do
  GOOS=${target%/*} GOARCH=${target#*/} go list -e -deps -tags nodynamic \
    -f '{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}} {{.Dir}}{{end}}{{end}}' ./cmd/og
done | sort -u >"$tmp.mods"

while read -r path version dir; do
  files=$(license_files "$dir")
  case $path in
  github.com/microsoft/TypeScript/tsc)
    version=$(git -C "$dir/.." rev-parse HEAD)
    files="$files $dir/../NOTICE.txt"
    ;;
  esac
  if [ -z "$files" ]; then
    echo "collect-notices: no license file for Go module $path" >&2
    echo x >>"$tmp.missing"
    continue
  fi
  # shellcheck disable=SC2086
  section "$path $version" $files
done <"$tmp.mods"

# Vendored Go (third_party/, not modules): goja_nodejs's require, rewritten
# for Sobek by scripts/vendor-goja-nodejs.sh.
section "github.com/dop251/goja_nodejs $(cat third_party/goja_nodejs/VERSION) (vendored Go: require/)" third_party/goja_nodejs/LICENSE

# Generated data: the RegExp v flag's emoji tables derive from Unicode's
# emoji data files (runtime/webapi/internal/genemoji).
section "Unicode emoji data (runtime/webapi/emoji_tables.go)" runtime/webapi/emoji_tables.LICENSE

# Vendored JS: one entry per package directory holding a package.json or a
# VERSION file (written by scripts/vendor-js.sh).
for tree in runtime/webapi/js/vendor runtime/nodeshim/vendor internal/jshost/js/vendor internal/frameworks/vite/js/vendor; do
  find "$tree" \( -name package.json -o -name VERSION \) -not -path '*/node_modules/*/node_modules/*' |
    xargs -n1 dirname | sort -u |
    while read -r dir; do
      # Skip nested package.json files (e.g. dist/esm/package.json).
      case $dir in */dist | */dist/* | */lib | */lib/* | */esm | */cjs) continue ;; esac
      name=${dir#"$tree"/}
      name=${name#node_modules/}
      files=$(license_files "$dir")
      if [ -z "$files" ]; then
        case $name in
        napi-wasm)
          # Ships no LICENSE file; its package.json declares MIT.
          printf '================================================================================\n%s\n\nLicensed under the MIT License (declared in its package.json; the package\nships no license file). Copyright (c) Devon Govett.\n\n' "$name" >>"$tmp"
          continue
          ;;
        esac
        echo "collect-notices: no license file for vendored $dir" >&2
        echo x >>"$tmp.missing"
        continue
      fi
      # shellcheck disable=SC2086
      section "$name (vendored JavaScript)" $files
    done
done

if [ -e "$tmp.missing" ]; then
  exit 1
fi
mkdir -p "$(dirname "$out")"
rm -f "$out"
mv "$tmp" "$out"
chmod 644 "$out"
echo "wrote $out"
