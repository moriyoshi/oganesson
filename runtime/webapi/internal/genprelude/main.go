// Command genprelude bundles the Web API prelude for each JavaScript engine.
// Run it via `go generate ./runtime/webapi`.
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strconv"

	"github.com/evanw/esbuild/pkg/api"
	"github.com/moriyoshi/oganesson/internal/gojatarget"
)

func main() {
	dir, err := os.Getwd() // go generate runs in the package directory
	if err != nil {
		fail(err)
	}
	for _, target := range []struct {
		file    string
		backend gojatarget.Backend
	}{
		{file: "prelude.js", backend: gojatarget.Sobek},
		{file: "prelude-ekuma.js", backend: gojatarget.Ekuma},
	} {
		generate(dir, target.file, target.backend)
	}
}

func generate(dir, file string, backend gojatarget.Backend) {
	opts := api.BuildOptions{
		EntryPoints:   []string{filepath.Join(dir, "js", "src", "index.ts")},
		Bundle:        true,
		Write:         false,
		GlobalName:    "__ogPrelude",
		LegalComments: api.LegalCommentsEndOfFile,
		LogLevel:      api.LogLevelWarning,
		Charset:       api.CharsetUTF8,
		Define:        map[string]string{"__ogNativeBuiltins": strconv.FormatBool(backend == gojatarget.Ekuma)},
		// The script's completion value is the install function.
		Banner: map[string]string{"js": "// Code generated by genprelude; DO NOT EDIT.\n(function () {"},
		Footer: map[string]string{"js": "return __ogPrelude.default;\n})()"},
	}
	backend.Apply(&opts)
	opts.MainFields = []string{"module", "main"}
	res := api.Build(opts)
	for _, e := range res.Errors {
		loc := ""
		if e.Location != nil {
			loc = fmt.Sprintf("%s:%d:%d: ", e.Location.File, e.Location.Line, e.Location.Column)
		}
		fmt.Fprintln(os.Stderr, loc+e.Text)
	}
	if len(res.Errors) > 0 {
		os.Exit(1)
	}
	out := string(res.OutputFiles[0].Contents)
	if backend == gojatarget.Sobek {
		out = gojatarget.HoldArrowArguments(out)
	}
	if err := os.WriteFile(filepath.Join(dir, file), []byte(out), 0o644); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "genprelude:", err)
	os.Exit(1)
}
