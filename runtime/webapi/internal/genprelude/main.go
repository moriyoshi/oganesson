// Command genprelude bundles runtime/webapi/js/src into prelude.js with
// esbuild. Run it via `go generate ./runtime/webapi`.
package main

import (
	"fmt"
	"os"
	"path/filepath"

	"github.com/evanw/esbuild/pkg/api"
	"github.com/moriyoshi/oganesson/internal/gojatarget"
)

func main() {
	dir, err := os.Getwd() // go generate runs in the package directory
	if err != nil {
		fail(err)
	}
	opts := api.BuildOptions{
		EntryPoints:   []string{filepath.Join(dir, "js", "src", "index.ts")},
		Bundle:        true,
		Write:         false,
		GlobalName:    "__ogPrelude",
		LegalComments: api.LegalCommentsEndOfFile,
		LogLevel:      api.LogLevelWarning,
		Charset:       api.CharsetUTF8,
		// The script's completion value is the install function.
		Banner: map[string]string{"js": "// Code generated by genprelude; DO NOT EDIT.\n(function () {"},
		Footer: map[string]string{"js": "return __ogPrelude.default;\n})()"},
	}
	gojatarget.Apply(&opts)
	opts.MainFields = []string{"module", "main"}
	res := api.Build(opts)
	for _, e := range res.Errors {
		loc := ""
		if e.Location != nil {
			loc = fmt.Sprintf("%s:%d:%d: ", e.Location.File, e.Location.Line, e.Location.Column)
		}
		fmt.Fprintln(os.Stderr, loc+e.Text)
	}
	if len(res.Errors) > 0 {
		os.Exit(1)
	}
	// Arrow functions reading their function's arguments (Goja bug).
	out := gojatarget.HoldArrowArguments(string(res.OutputFiles[0].Contents))
	if err := os.WriteFile(filepath.Join(dir, "prelude.js"), []byte(out), 0o644); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "genprelude:", err)
	os.Exit(1)
}
