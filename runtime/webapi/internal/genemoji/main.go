// Command genemoji writes emoji_tables.go: the ECMAScript properties of
// strings (the RegExp v flag's \p{RGI_Emoji} and the emoji sequence
// properties, ECMA-262 "Binary Unicode properties of strings") from the
// Unicode emoji data files of the release Node 24 implements. Run by
// go generate ./runtime/webapi/ (it downloads the files).
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

const unicodeVersion = "17.0.0"

var files = []string{"emoji-sequences.txt", "emoji-zwj-sequences.txt"}

// The properties ECMAScript defines, and RGI_Emoji, their union.
var properties = []string{
	"Basic_Emoji", "Emoji_Keycap_Sequence", "RGI_Emoji_Flag_Sequence",
	"RGI_Emoji_Modifier_Sequence", "RGI_Emoji_Tag_Sequence", "RGI_Emoji_ZWJ_Sequence",
}

type property struct {
	points  []rune   // single code points
	strings []string // sequences of two or more code points
}

func main() {
	props := map[string]*property{}
	for _, p := range properties {
		props[p] = &property{}
	}
	for _, f := range files {
		url := "https://www.unicode.org/Public/" + unicodeVersion + "/emoji/" + f
		resp, err := http.Get(url)
		if err != nil {
			fail(err)
		}
		if resp.StatusCode != 200 {
			fail(fmt.Errorf("%s: %s", url, resp.Status))
		}
		sc := bufio.NewScanner(resp.Body)
		for sc.Scan() {
			line := sc.Text()
			if i := strings.IndexByte(line, '#'); i >= 0 {
				line = line[:i]
			}
			fields := strings.Split(line, ";")
			if len(fields) < 2 {
				continue
			}
			p := props[strings.TrimSpace(fields[1])]
			if p == nil {
				continue
			}
			cps := strings.TrimSpace(fields[0])
			if lo, hi, ok := strings.Cut(cps, ".."); ok {
				for r := hex(lo); r <= hex(hi); r++ {
					p.points = append(p.points, r)
				}
				continue
			}
			var seq []rune
			for _, c := range strings.Fields(cps) {
				seq = append(seq, hex(c))
			}
			if len(seq) == 1 {
				p.points = append(p.points, seq[0])
			} else {
				p.strings = append(p.strings, string(seq))
			}
		}
		resp.Body.Close()
		if err := sc.Err(); err != nil {
			fail(err)
		}
	}
	all := &property{}
	for _, p := range properties {
		all.points = append(all.points, props[p].points...)
		all.strings = append(all.strings, props[p].strings...)
	}
	props["RGI_Emoji"] = all

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by genemoji from Unicode %s emoji data; DO NOT EDIT.\n\npackage webapi\n\n", unicodeVersion)
	b.WriteString("// emojiProperties are the ECMAScript properties of strings: single code\n// points as [lo, hi] ranges, and the strings of two or more code points.\n")
	b.WriteString("var emojiProperties = map[string]emojiProperty{\n")
	names := append([]string{"RGI_Emoji"}, properties...)
	sort.Strings(names)
	for _, n := range names {
		p := props[n]
		fmt.Fprintf(&b, "\t%q: {\n\t\tranges: []rune{", n)
		for i, r := range ranges(p.points) {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "%#x", r)
		}
		b.WriteString("},\n\t\tstrings: []string{")
		strs := dedupe(p.strings)
		for i, s := range strs {
			if i > 0 {
				b.WriteString(", ")
			}
			b.WriteString(strconv.QuoteToASCII(s))
		}
		b.WriteString("},\n\t},\n")
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		fail(err)
	}
	dir, err := os.Getwd() // go generate runs in the package directory
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "emoji_tables.go"), out, 0o644); err != nil {
		fail(err)
	}
	// The tables derive from Unicode's data files: their license goes
	// with them (scripts/collect-notices.sh includes it).
	resp, err := http.Get("https://www.unicode.org/license.txt")
	if err != nil {
		fail(err)
	}
	defer resp.Body.Close()
	lic, err := io.ReadAll(resp.Body)
	if err != nil || resp.StatusCode != 200 {
		fail(fmt.Errorf("unicode license: %v %s", err, resp.Status))
	}
	if err := os.WriteFile(filepath.Join(dir, "emoji_tables.LICENSE"), lic, 0o644); err != nil {
		fail(err)
	}
}

func hex(s string) rune {
	v, err := strconv.ParseUint(s, 16, 32)
	if err != nil {
		fail(err)
	}
	return rune(v)
}

// ranges collapses code points into sorted [lo, hi] pairs.
func ranges(points []rune) []rune {
	sort.Slice(points, func(i, j int) bool { return points[i] < points[j] })
	var out []rune
	for _, r := range points {
		if n := len(out); n > 0 && r <= out[n-1]+1 {
			if r > out[n-1] {
				out[n-1] = r
			}
			continue
		}
		out = append(out, r, r)
	}
	return out
}

func dedupe(ss []string) []string {
	seen := map[string]bool{}
	var out []string
	for _, s := range ss {
		if !seen[s] {
			seen[s] = true
			out = append(out, s)
		}
	}
	sort.Strings(out)
	return out
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "genemoji:", err)
	os.Exit(1)
}
