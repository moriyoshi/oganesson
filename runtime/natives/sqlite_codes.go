// modernc writes "errstr: errmsg (rc)" (or "errstr (rc)"); better-sqlite3's
// message is SQLite's errmsg alone.
var moderncMessage = regexp.MustCompile(`^[^:]*: (.*) \(\d+\)( \(SQLITE_BUSY\))?$`)

// sqliteErrorInfo is an error's better-sqlite3 code and message.
func sqliteErrorInfo(err error) (code, message string) {
	code, message = "SQLITE_ERROR", err.Error()
	var se *sqlite.Error
	if !errors.As(err, &se) {
		return code, message
	}
	if name, ok := sqliteCodeNames[se.Code()]; ok {
		code = name
	} else if name, ok := sqliteCodeNames[se.Code()&0xff]; ok {
		code = name
	}
	if m := moderncMessage.FindStringSubmatch(se.Error()); m != nil {
		message = m[1]
	}
	return code, message
}
